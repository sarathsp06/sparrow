// TargetInfo describes a supported target.
type TargetInfo struct {
	Target
	ID string `json:"id"`
	// Name is a display name, e.g. "Go (net/http)".
	Name string `json:"name"`
	// Runtime is the minimum runtime the generated project needs.
	Runtime string `json:"runtime"`
}

// File is one generated file.
type File struct {
	// Path is slash-separated and relative to the project root.
	Path    string `json:"path"`
	Content string `json:"content"`
	// Mode is the Unix permission bits, e.g. 0o644.
	Mode uint32 `json:"mode"`
}

// Output is a generated receiver project.
type Output struct {
	// Files are sorted by Path.
	Files []File `json:"files"`
	Spec  Spec   `json:"spec"`
	// Run and Test are shell commands, run from the project root.
	Run  string `json:"run"`
	Test string `json:"test"`
}

type targetDef struct {
	info  TargetInfo
	run   func(g *gen) string
	test  string
	build func(g *gen) (map[string]any, []File, error)
}

var targets = []targetDef{goTarget, pythonTarget, nodeTarget}

// Targets lists the supported targets, sorted by ID.
func Targets() []TargetInfo {
	out := make([]TargetInfo, 0, len(targets))
	for _, t := range targets {
		out = append(out, t.info)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out
}

func targetInfo(t Target) (targetDef, bool) {
	for _, def := range targets {
		if def.info.Target == t {
			return def, true
		}
	}
	return targetDef{}, false
}

// gen is one generation run.
type gen struct {
	in    Input
	plans []*plan
	spec  Spec
}

// Generate builds a receiver project for in.Target. The same Input always
// produces byte-identical Output.
func Generate(in Input) (Output, error) {
	if err := in.validate(); err != nil {
		return Output{}, err
	}
	def, _ := targetInfo(in.Target)
	if in.SparrowVersion == "" {
		in.SparrowVersion = "dev"
	}

	plans := make([]*plan, 0, len(in.Subscriptions))
	for _, s := range in.Subscriptions {
		p := analyze(s)
		p.settleModel()
		plans = append(plans, p)
	}
	assignNames(plans)

	creds := testCreds(in.Webhook.ID)
	spec := Spec{
		SpecVersion: SpecVersion,
		Target:      def.info.ID,
		Webhook: SpecWebhook{
			ID:            in.Webhook.ID,
			Consumer:      in.Webhook.Consumer,
			SigningScheme: in.Webhook.SigningScheme,
		},
		Receiver: SpecReceiver{
			WebhookPath:        WebhookPath,
			HealthPath:         HealthPath,
			TestModeEnv:        EnvTestMode,
			PortEnv:            EnvPort,
			DefaultPort:        8000,
			ToleranceSeconds:   DefaultToleranceSeconds,
			DedupCapacity:      DefaultDedupCapacity,
			DispatchHeaders:    []string{"X-Sparrow-Subscription-ID", "X-Sparrow-Event-Type"},
			UnknownEventStatus: UnknownEventStatus,
		},
		Test: creds,
	}
	if in.Webhook.SigningScheme == SchemeEd25519 {
		spec.Webhook.PublicKey = strings.ToLower(in.Webhook.Ed25519PublicKey)
		spec.Receiver.PublicKeyEnv = EnvPublicKey
	} else {
		spec.Receiver.SecretEnv = EnvSecret
	}
	for _, p := range plans {
		spec.Subscriptions = append(spec.Subscriptions, SpecSubscription{
			ID:           p.Sub.ID,
			EventType:    p.Sub.EventType,
			EventVersion: p.Sub.EventVersion,
			Handler:      handlerName(p),
			Format:       p.Format,
			ContentType:  p.ContentType,
			Model:        p.Model,
			ModelSource:  p.ModelSource,
			Notes:        p.Notes,
			RenderError:  p.RenderError,
		})
	}
	spec.Vectors = buildVectors(plans, in.Webhook.SigningScheme, creds)

	g := &gen{in: in, plans: plans, spec: spec}
	data, files, err := def.build(g)
	if err != nil {
		return Output{}, err
	}
	data["TargetName"] = def.info.Name
	data["Run"] = def.run(g)
	data["Test"] = def.test
	rendered, err := g.renderTemplates(def.info.ID, data)
	if err != nil {
		return Output{}, err
	}
	files = append(files, rendered...)
	specJSON, err := json.MarshalIndent(spec, "", "  ")
	if err != nil {
		return Output{}, fmt.Errorf("receivercode: encode spec: %w", err)
	}
	files = append(files, File{Path: "testdata/spec.json", Content: string(specJSON) + "\n", Mode: 0o644})
	sort.Slice(files, func(i, j int) bool { return files[i].Path < files[j].Path })
	return Output{Files: files, Spec: spec, Run: def.run(g), Test: def.test}, nil
}

// header is the first-line comment of every generated file that can hold
// one. It names the version and target and deliberately has no timestamp.
func (g *gen) header() string {
	return fmt.Sprintf("Generated by Sparrow %s (receiver code, target %s). Edit freely: Sparrow never rewrites this project.",
		g.in.SparrowVersion, g.spec.Target)
}

// envPrefix is the environment a run command needs: the secret for HMAC,
// nothing for Ed25519 (the public key is embedded).
func (g *gen) envPrefix() string {
	if g.in.Webhook.SigningScheme == SchemeEd25519 {
		return ""
	}
	return EnvSecret + "=<your webhook secret> "
}

// renderTemplates renders the shared targets/*.tmpl and the target's own
// targets/<id>/**/*.tmpl. A template's output path is its path below that
// directory without ".tmpl", with a leading "_" turned into ".".
func (g *gen) renderTemplates(id string, data map[string]any) ([]File, error) {
	var files []File
	err := fs.WalkDir(targetFS, "targets", func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if p != "targets" && p != path.Join("targets", id) && path.Dir(p) == "targets" {
				return fs.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(p, ".tmpl") {
			return nil
		}
		root := "targets"
		if strings.HasPrefix(p, path.Join("targets", id)+"/") {
			root = path.Join("targets", id)
		}
		src, err := targetFS.ReadFile(p)
		if err != nil {
			return err
		}
		t, err := template.New(path.Base(p)).Delims("[[", "]]").Funcs(templateFuncs).Parse(string(src))
		if err != nil {
			return fmt.Errorf("receivercode: parse %s: %w", p, err)
		}
		var buf bytes.Buffer
		if err := t.Execute(&buf, data); err != nil {
			return fmt.Errorf("receivercode: render %s: %w", p, err)
		}
		rel := strings.TrimSuffix(strings.TrimPrefix(p, root+"/"), ".tmpl")
		dir, base := path.Split(rel)
		if strings.HasPrefix(base, "_") {
			base = "." + base[1:]
		}
		content, err := formatSource(dir+base, buf.Bytes())
		if err != nil {
			return err
		}
		files = append(files, File{Path: dir + base, Content: content, Mode: fileMode(base)})
		return nil
	})
	return files, err
}

func fileMode(base string) uint32 {
	if strings.HasSuffix(base, ".sh") {
		return 0o755
	}
	return 0o644
}

var templateFuncs = template.FuncMap{
	"snake": snake,
	"quote": func(s string) string {
		b, _ := json.Marshal(s)
		return string(b)
	},
	"sentence": func(s string) string { return capitalize(s) + "." },
	"trimNL":   func(s string) string { return strings.TrimRight(s, "\n") },
	"comment": func(prefix string, lines []string) string {
		var b strings.Builder
		for _, l := range lines {
			for _, wrapped := range wrap(capitalize(commentText(l))+".", 76) {
				b.WriteString(prefix + wrapped + "\n")
			}
		}
		return b.String()
	},
}

func capitalize(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

// wrap breaks s into lines of at most width runes at spaces.
func wrap(s string, width int) []string {
	var lines []string
	var cur strings.Builder
	for _, word := range strings.Fields(s) {
		if cur.Len() > 0 && cur.Len()+1+len(word) > width {
			lines = append(lines, cur.String())
			cur.Reset()
		}
		if cur.Len() > 0 {
			cur.WriteByte(' ')
		}
		cur.WriteString(word)
	}
	if cur.Len() > 0 {
		lines = append(lines, cur.String())
	}
	return lines
}
